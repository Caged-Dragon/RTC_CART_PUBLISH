  (92,6,'Premium Pick','Premium Favourite','Premium fancy-variety choice',94.0),
  (112,7,'Kids Pick','Kids Favourite','Novelty-style pick for younger celebrations',93.0),
  (118,8,'Combo Pick','Starter Gift Box','Easy all-in-one assortment',92.0),
  (122,9,'Combo Pick','Family Gift Box','Balanced family celebration assortment',91.0),
  (126,10,'Premium Pick','Royal Celebration','Large-format premium assortment',90.0)
