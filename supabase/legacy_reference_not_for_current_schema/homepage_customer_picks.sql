-- RedThunder storefront: customer-focused homepage merchandising.
-- Additive only. Does not alter public.products, orders, cart, checkout, auth or RLS.
-- Website isolation: website_key is fixed to 'cart'.

create table if not exists public.homepage_customer_picks (
  id bigint generated by default as identity primary key,
  website_key text not null default 'cart',
  product_id uuid not null references public.products(id) on delete cascade,
  display_order integer not null default 0 check (display_order >= 0),
  is_active boolean not null default true,
  badge_text text,
  customer_label text,
  customer_reason text,
  customer_score numeric(5,2) check (customer_score is null or (customer_score >= 0 and customer_score <= 100)),
  rating_stars numeric(2,1) check (rating_stars is null or (rating_stars >= 0 and rating_stars <= 5)),
  rating_count integer not null default 0 check (rating_count >= 0),
  admin_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (website_key, product_id),
  check (website_key = 'cart')
);

create index if not exists homepage_customer_picks_active_order_idx
  on public.homepage_customer_picks (website_key, is_active, display_order, id);

alter table public.homepage_customer_picks enable row level security;
revoke all on public.homepage_customer_picks from anon, authenticated;
grant select on public.homepage_customer_picks to anon, authenticated;
grant insert, update, delete on public.homepage_customer_picks to authenticated;

drop policy if exists homepage_customer_picks_public_read on public.homepage_customer_picks;
create policy homepage_customer_picks_public_read
  on public.homepage_customer_picks for select to anon, authenticated
  using (website_key = 'cart' and is_active = true);

drop policy if exists homepage_customer_picks_admin_write on public.homepage_customer_picks;
create policy homepage_customer_picks_admin_write
  on public.homepage_customer_picks for all to authenticated
  using ((select private.is_admin()) and website_key = 'cart')
  with check ((select private.is_admin()) and website_key = 'cart');

-- Optional starter merchandising rows. These reference existing products only.
-- rating_stars/rating_count intentionally start empty/zero because the current review table has no reviews.
